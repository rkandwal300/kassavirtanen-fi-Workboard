export const FETCH_TASKS_REQUEST = 'FETCH_TASKS_REQUEST';
export const FETCH_TASKS_SUCCESS = 'FETCH_TASKS_SUCCESS';
export const FETCH_TASKS_FAILURE = 'FETCH_TASKS_FAILURE';
export const FETCH_USERS_REQUEST = 'FETCH_USERS_REQUEST';
export const FETCH_USERS_SUCCESS = 'FETCH_USERS_SUCCESS';
export const FETCH_USERS_FAILURE = 'FETCH_USERS_FAILURE';
export const FETCH_PROJECTS_REQUEST = 'FETCH_PROJECTS_REQUEST';
export const FETCH_PROJECTS_SUCCESS = 'FETCH_PROJECTS_SUCCESS';
export const FETCH_PROJECTS_FAILURE = 'FETCH_PROJECTS_FAILURE';
export const CREATE_TASK_REQUEST = 'CREATE_TASK_REQUEST';
export const CREATE_TASK_SUCCESS = 'CREATE_TASK_SUCCESS';
export const CREATE_TASK_FAILURE = 'CREATE_TASK_FAILURE';
export const CREATE_TASK_OPTIMISTIC = 'CREATE_TASK_OPTIMISTIC';
export const UPDATE_TASK_REQUEST = 'UPDATE_TASK_REQUEST';
export const UPDATE_TASK_SUCCESS = 'UPDATE_TASK_SUCCESS';
export const UPDATE_TASK_FAILURE = 'UPDATE_TASK_FAILURE';
export const UPDATE_TASK_OPTIMISTIC = 'UPDATE_TASK_OPTIMISTIC';
export const DELETE_TASK_REQUEST = 'DELETE_TASK_REQUEST';
export const DELETE_TASK_SUCCESS = 'DELETE_TASK_SUCCESS';
export const DELETE_TASK_FAILURE = 'DELETE_TASK_FAILURE';
export const DELETE_TASK_OPTIMISTIC = 'DELETE_TASK_OPTIMISTIC';

export const fetchTasksRequest = (filters = {}) => ({ type: FETCH_TASKS_REQUEST, filters });
export const fetchTasksSuccess = (tasks) => ({ type: FETCH_TASKS_SUCCESS, tasks });
export const fetchTasksFailure = (error) => ({ type: FETCH_TASKS_FAILURE, error });
export const fetchUsersRequest = () => ({ type: FETCH_USERS_REQUEST });
export const fetchUsersSuccess = (users) => ({ type: FETCH_USERS_SUCCESS, users });
export const fetchUsersFailure = (error) => ({ type: FETCH_USERS_FAILURE, error });
export const fetchProjectsRequest = () => ({ type: FETCH_PROJECTS_REQUEST });
export const fetchProjectsSuccess = (projects) => ({ type: FETCH_PROJECTS_SUCCESS, projects });
export const fetchProjectsFailure = (error) => ({ type: FETCH_PROJECTS_FAILURE, error });
export const createTaskRequest = (task, draftKey) => ({ type: CREATE_TASK_REQUEST, task, draftKey });
export const createTaskOptimistic = (task) => ({ type: CREATE_TASK_OPTIMISTIC, task });
export const createTaskSuccess = (tempId, task) => ({ type: CREATE_TASK_SUCCESS, tempId, task });
export const createTaskFailure = (tempId, error) => ({ type: CREATE_TASK_FAILURE, tempId, error });
export const updateTaskRequest = (taskId, updates, draftKey) => ({ type: UPDATE_TASK_REQUEST, taskId, updates, draftKey });
export const updateTaskOptimistic = (taskId, updates) => ({ type: UPDATE_TASK_OPTIMISTIC, taskId, updates });
export const updateTaskSuccess = (taskId, task) => ({ type: UPDATE_TASK_SUCCESS, taskId, task });
export const updateTaskFailure = (taskId, originalTask, error) => ({ type: UPDATE_TASK_FAILURE, taskId, originalTask, error });
export const deleteTaskRequest = (taskId) => ({ type: DELETE_TASK_REQUEST, taskId });
export const deleteTaskOptimistic = (taskId, task, index) => ({ type: DELETE_TASK_OPTIMISTIC, taskId, task, index });
export const deleteTaskSuccess = (taskId) => ({ type: DELETE_TASK_SUCCESS, taskId });
export const deleteTaskFailure = (taskId, task, index, error) => ({ type: DELETE_TASK_FAILURE, taskId, task, index, error });
